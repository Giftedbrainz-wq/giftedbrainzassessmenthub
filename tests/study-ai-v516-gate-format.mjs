import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const get=path=>readFileSync(new URL(path,import.meta.url),'utf8');
const ui=get('../app.js'),server=get('../edge-functions/api/index.js');
const css=get('../study-ai-richtext-v51.6.css'),html=get('../index.html');
const formatter=get('../study-ai-format-v51.6.js');
assert.match(server,/progress\.answers\[questionId\]==null/);
assert.match(server,/Answer this question and view the correct answer before using Ask AI/);
assert.match(server,/question_ids\?\.includes\(questionId\)/);
assert.match(server,/feedbackMap\[id\]/);
assert.match(ui,/function poolStudyAiUnlocked\(q\)/);
assert.match(ui,/if\(!poolStudyAiUnlocked\(q\)\)return/);
assert.match(ui,/\$\{poolStudyAiUnlocked\(q\)\?`<div class="gb-study-ai-entry"/);
assert.match(ui,/state\.studentPoolFeedbackMap=r\.feedbackMap\|\|\{\}/);
assert.match(css,/\.gb-study-ai-panel\s*\{[\s\S]*?border-radius:24px/);
assert.match(css,/@media\(max-width:700px\)/);
assert.match(html,/study-ai-richtext-v51\.6\.css/);
assert.match(html,/study-ai-format-v51\.6\.js/);
console.log('PASS AI unlocks only after confirmed answer feedback; desktop/mobile dialogue has rounded corners');
const ctx={globalThis:null,console};ctx.globalThis=ctx;vm.createContext(ctx);vm.runInContext(formatter,ctx);
const escapeHtml=s=>String(s).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const fakeKatex={renderToString:(tex,options)=>`<span class="katex${options.displayMode?' display':''}">typeset</span>`};
const sample='**Key idea**\n\nUse the formula.\n\n**Working**\n1. Substitute: $x=\\frac{1}{2}$.\n2. Multiply: $$2\\times 3=6$$.\n\n**Final answer**\nThe answer is **B**.';
const rendered=ctx.GiftedStudyAiFormat(sample,{mathHtml:escapeHtml,katex:fakeKatex});
assert.match(rendered,/<h3 class="gb-ai-section-heading">Key idea<\/h3>/);
assert.match(rendered,/<ol class="gb-ai-list">/);
assert.match(rendered,/class="katex/);
assert.doesNotMatch(rendered,/(?:\$\$|\$x=|\\frac\{1\})/);
const malicious=ctx.GiftedStudyAiFormat('**Explanation**\n<script>alert(1)</script>\n- <img src=x onerror=alert(1)>',{mathHtml:escapeHtml,katex:fakeKatex});
assert.doesNotMatch(malicious,/<script>|<img/);
assert.match(malicious,/&lt;script&gt;/);
console.log('PASS AI responses have labelled sections, ordered steps, rendered maths, no raw LaTeX or unsafe HTML');
